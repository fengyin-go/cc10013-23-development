def _explain(samples: list[dict[str, Any]], abnormal_items: list[str]) -> str:
    parts = [
        f"{s['指标类型']}{s['判定']}（实测 {s['样本值']}，阈值 {s['阈值']}，样本 {s['样本编号']}）"
        for s in samples
    ]
    text = '联合判定：' + '；'.join(parts)
    text += (
        f"。异常项：{'、'.join(abnormal_items)}"
        if abnormal_items
        else '。三项指标均在阈值内。'
    )
    return text


